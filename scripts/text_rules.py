def name_of(title, text):
    m = re.match(r"^[《]?([^（(《》，。、\s=]{2,20})[》]?[（(，。 是为]", text)
    n = m.group(1) if m else re.sub(r"\s*\(.*\)$", "", title)
    return re.sub(r"\s*[\(（].*$", "", n)


def sentences(text):
    body = re.split(r"\n==+ *(参考|参见|外部链接|注释|延伸阅读|相关条目|参考文献|脚注)", text)[0]
    return [s.strip() for s in re.split(r"(?<=[。！？；])|\n+", body) if len(s.strip()) >= 6 and not s.startswith("==")]


def dynasties(cats):
    found = []
    for name, pat in DYNASTY:
        if any(re.search(f"({pat})", c) and re.search(r"書法家|书法家|书家|書家|人物|人$", c) for c in cats):
            found.append(name)
    return found
